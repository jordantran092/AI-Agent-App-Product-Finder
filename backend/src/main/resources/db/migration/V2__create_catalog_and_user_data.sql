CREATE TABLE retailer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    brand VARCHAR(120) NOT NULL,
    model VARCHAR(120) NOT NULL UNIQUE,
    category VARCHAR(40) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    image_url VARCHAR(1000),
    attributes JSON NOT NULL,
    discontinued BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE listing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product (id),
    retailer_id BIGINT NOT NULL REFERENCES retailer (id),
    price NUMERIC(12, 2),
    condition VARCHAR(40) NOT NULL,
    in_stock BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_listing_product_retailer UNIQUE (product_id, retailer_id),
    CONSTRAINT ck_listing_price_nonnegative CHECK (price IS NULL OR price >= 0)
);

CREATE TABLE price_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listing (id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_price_point_price_nonnegative CHECK (price >= 0)
);

CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product (id),
    retailer_id BIGINT NOT NULL REFERENCES retailer (id),
    rating NUMERIC(2, 1) NOT NULL,
    text VARCHAR(4000) NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_review_rating CHECK (rating >= 0 AND rating <= 5)
);

CREATE TABLE user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user (id),
    budget NUMERIC(12, 2),
    CONSTRAINT ck_user_profile_budget CHECK (budget IS NULL OR budget >= 0)
);

CREATE TABLE profile_excluded_brand (
    profile_id BIGINT NOT NULL REFERENCES user_profile (id) ON DELETE CASCADE,
    brand VARCHAR(120) NOT NULL,
    PRIMARY KEY (profile_id, brand)
);

CREATE TABLE profile_allowed_condition (
    profile_id BIGINT NOT NULL REFERENCES user_profile (id) ON DELETE CASCADE,
    condition_value VARCHAR(40) NOT NULL,
    PRIMARY KEY (profile_id, condition_value)
);

CREATE TABLE saved_list (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user (id),
    share_token VARCHAR(128) UNIQUE
);

CREATE TABLE saved_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saved_list_id BIGINT NOT NULL REFERENCES saved_list (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES product (id),
    note VARCHAR(4000),
    trust_label VARCHAR(200),
    CONSTRAINT uk_saved_item_list_product UNIQUE (saved_list_id, product_id)
);

